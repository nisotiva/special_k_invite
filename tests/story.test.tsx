import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MotionConfig } from 'motion/react';
import { SceneManager } from '../src/scenes/SceneManager';
import { Calendar } from '../src/story/Calendar';
import { dateKey, isFutureAppointment, parseDate, timeOptions } from '../src/story/dateUtils';
import { readProgress, STORAGE_KEY } from '../src/story/progress';
vi.mock('../src/config', () => ({ discordWebhookUrl: '' }));
afterEach(() => { cleanup(); sessionStorage.clear(); vi.restoreAllMocks(); });
describe('Complete story', () => {
  it('preserves the existing Regalia flow and goes through every new scene to the honest unconfigured form', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch');
    render(<MotionConfig reducedMotion="user"><SceneManager /></MotionConfig>);
    const start = screen.getByRole('button', { name: 'Начать проверку' });
    fireEvent.click(start);
    fireEvent.click(start); // Outgoing controls cannot skip the next scene.
    const regalia = await screen.findByRole('button', { name: 'Выбрать Regalia' });
    await waitFor(() => expect(regalia.hasAttribute('disabled')).toBe(false));
    fireEvent.click(regalia);
    fireEvent.click(await screen.findByRole('button', { name: 'Продолжить' }, { timeout: 2000 }));
    const rose = await screen.findByRole('button', { name: 'Роза', exact: true });
    fireEvent.click(rose);
    expect(screen.getByRole('status').textContent).toContain('Ты уверена');
    expect(rose.querySelector('img')).not.toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Ни один. Все прекрасны' }));
    expect(rose.hasAttribute('disabled')).toBe(true);
    expect(document.querySelector('.flower-stage')?.classList.contains('is-bouquet')).toBe(true);
    fireEvent.click(await screen.findByRole('button', { name: 'Продолжить' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Декамерон' }));
    expect(screen.getByRole('status').textContent).toContain('другую историю');
    fireEvent.click(screen.getByRole('button', { name: 'Тысяча и одна ночь' }));
    await waitFor(() => expect([...document.querySelectorAll('.background-image')].some(element => element.getAttribute('src')?.includes('palace-dawn.webp'))).toBe(true));
    fireEvent.click(await screen.findByRole('button', { name: 'Продолжить' }));
    fireEvent.click(await screen.findByRole('button', { name: /Обязывать доверителя/ }));
    expect(screen.getByRole('status').textContent).toContain('В документе такого пункта не обнаружено');
    fireEvent.click(screen.getByRole('button', { name: /Назначать личные встречи/ }));
    expect(screen.getByText('ПОЛНОМОЧИЯ ПОДТВЕРЖДЕНЫ')).toBeDefined();
    fireEvent.click(await screen.findByRole('button', { name: 'Продолжить' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Ужасы' }));
    expect(screen.getByRole('status').textContent).toContain('Попробуй ещё раз');
    fireEvent.click(screen.getByRole('button', { name: 'Мюзиклы' }));
    await screen.findByText('Да. Именно мюзиклы.');
    await screen.findByRole('heading', { name: 'Но...' }, { timeout: 2000 });
    await screen.findByRole('heading', { name: /И мне кажется, у меня впервые появилось желание/ }, { timeout: 3000 });
    fireEvent.click(await screen.findByRole('button', { name: 'И что дальше?' }));
    await screen.findByRole('heading', { name: 'Осталась одна формальность' });
    const day = new Date(); day.setDate(day.getDate() + 2);
    if (day.getMonth() !== new Date().getMonth()) fireEvent.click(screen.getByRole('button', { name: 'Следующий месяц' }));
    fireEvent.click(screen.getByRole('button', { name: new Intl.DateTimeFormat('ru-RU', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(day) }));
    fireEvent.change(screen.getByLabelText('Время встречи'), { target: { value: '20:45' } });
    fireEvent.click(screen.getByRole('button', { name: 'Воспользоваться полномочиями' }));
    expect(screen.getByText(/Скопируйте выбранную дату и время и отправьте/)).toBeDefined();
    expect(fetchMock).not.toHaveBeenCalled();
    expect(screen.queryByRole('heading', { name: /Ваше предложение принято/ })).toBeNull();
    expect(JSON.parse(sessionStorage.getItem(STORAGE_KEY)!).scene).toBe('date');
    const copyMock = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: copyMock } });
    fireEvent.click(screen.getByRole('button', { name: 'Скопировать дату и время' }));
    await waitFor(() => expect(copyMock).toHaveBeenCalledWith(expect.stringContaining('20:45')));
  }, 20000);
});
describe('Calendar and session', () => {
  it('starts weeks on Monday, disables past days, navigates years, and supports arrow keys', () => {
    const onSelect = vi.fn();
    render(<Calendar selected="" onSelect={onSelect} today={new Date(2026, 11, 30)} />);
    const previous = screen.getByRole('button', { name: 'Предыдущий месяц' });
    expect(previous.hasAttribute('disabled')).toBe(true);
    const past = screen.getByRole('button', { name: /29 декабря 2026/ });
    expect(past.hasAttribute('disabled')).toBe(true);
    const today = screen.getByRole('button', { name: /30 декабря 2026/ });
    fireEvent.keyDown(today, { key: 'ArrowRight' });
    expect(document.activeElement?.getAttribute('aria-label')).toContain('31 декабря');
    fireEvent.keyDown(document.activeElement!, { key: 'ArrowRight' });
    expect(screen.getByText('январь 2027 г.')).toBeDefined();
    expect(document.activeElement?.getAttribute('aria-label')).toContain('1 января');
    fireEvent.click(document.activeElement!);
    expect(onSelect).toHaveBeenCalledWith('2027-01-01');
    fireEvent.click(screen.getByRole('button', { name: 'Предыдущий месяц' }));
    expect(screen.getByText('декабрь 2026 г.')).toBeDefined();
  });
  it('handles local dates, invalid leap days, all 96 time choices, and past appointment times', () => {
    expect(dateKey(new Date(2026, 10, 5))).toBe('2026-11-05');
    expect(parseDate('2026-02-29')).toBeNull();
    expect(parseDate('2028-02-29')).not.toBeNull();
    expect(timeOptions).toHaveLength(96);
    expect(timeOptions[95]).toBe('23:45');
    const now = new Date(2026, 10, 5, 16, 30);
    expect(isFutureAppointment('2026-11-05', '16:15', now)).toBe(false);
    expect(isFutureAppointment('2026-11-05', '16:30', now)).toBe(false);
    expect(isFutureAppointment('2026-11-05', '16:45', now)).toBe(true);
    expect(isFutureAppointment('2026-11-06', '00:00', now)).toBe(true);
    expect(isFutureAppointment('2026-11-06', '12:07', now)).toBe(false);
  });
  it('restores solved stages without repeating the automatic Regalia animation and rejects broken storage', () => {
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify({ scene: 'question', completed: ['question'] }));
    expect(readProgress().scene).toBe('flowers');
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify({ scene: 'confirmation', completed: [] }));
    expect(readProgress().scene).toBe('date');
    sessionStorage.setItem(STORAGE_KEY, 'broken');
    expect(readProgress().scene).toBe('welcome');
  });
});
